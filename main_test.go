package main

import (
	"testing"
)

func TestGetPathLength(t *testing.T) {
	tests := []struct {
		file string
		want int
	}{
		{ // example
			`....#.....
.........#
..........
..#.......
.......#..
..........
.#..^.....
........#.
#.........
......#...`, 41,
		},
		{ // 1 turn
			`#....
.....
.....
.....
^....`, 8,
		},
		{ // 2 turns
			`#....
....#
.....
.....
^....`, 10},
		{ // 3 turns
			`#....
....#
.....
.....
^..#.`, 11},
		{ // 4 turns
			`#....
....#
.....
.#...
^..#.`, 12},
		{ // multiple obstacles
			`..........
....#.....
.#......#.
..........
#.........
.#.....##.
.........#
..........
.^.#......
........#.`, 38},
		{ // bounce back
			`#....
.#...
.....
.....
^....`, 4},
		{ // bounce back after turn
			`#....
....#
...#.
.....
^....`, 7},
	}

	for _, test := range tests {
		got := getPathLength(test.file)
		if got != test.want {
			t.Errorf("getPathLength(), got:%v, want:%v", got, test.want)
		}
	}
}
